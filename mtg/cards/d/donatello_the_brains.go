// DonatelloTheBrains is the card definition for Donatello, the Brains.
//
// Type: Legendary Creature — Mutant Ninja Turtle
// Cost: {2}{U}
//
// Oracle text:
//
//	If one or more tokens would be created under your control, those tokens plus a Mutagen token are created instead.
//	Partner—Character select (You can have two commanders if both have this ability.)
var DonatelloTheBrains = newDonatelloTheBrains

func newDonatelloTheBrains() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Blue),
		CardFace: game.CardFace{
			Name: "Donatello, the Brains",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.U,
			}),
			Colors:     []color.Color{color.Blue},
			Supertypes: []types.Super{types.Legendary},
			Types:      []types.Card{types.Creature},
			Subtypes:   []types.Sub{types.Mutant, types.Ninja, types.Turtle},
			Power:      opt.Val(game.PT{Value: 2}),
			Toughness:  opt.Val(game.PT{Value: 4}),
			StaticAbilities: []game.StaticAbility{
				game.PartnerStaticBody,
			},
			ReplacementAbilities: []game.ReplacementAbility{
				game.TokenCreationReplacementFiltered("If one or more tokens would be created under your control, those tokens plus a Mutagen token are created instead.", &game.TokenCreationReplacementSpec{Multiplier: 1, Addend: 1, AddendDef: donatelloTheBrainsToken, Filter: game.TriggerControllerYou}),
			},
			OracleText: `
			If one or more tokens would be created under your control, those tokens plus a Mutagen token are created instead.
			Partner—Character select (You can have two commanders if both have this ability.)
		`,
		},
	}
}

var donatelloTheBrainsToken = newDonatelloTheBrainsToken()


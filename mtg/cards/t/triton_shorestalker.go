// TritonShorestalker is the card definition for Triton Shorestalker.
//
// Type: Creature — Merfolk Rogue
// Cost: {U}
//
// Oracle text:
//
//	This creature can't be blocked.
var TritonShorestalker = newTritonShorestalker

func newTritonShorestalker() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Blue),
		CardFace: game.CardFace{
			Name: "Triton Shorestalker",
			ManaCost: opt.Val(cost.Mana{
				cost.U,
			}),
			Colors:    []color.Color{color.Blue},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Merfolk, types.Rogue},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 1}),
			StaticAbilities: []game.StaticAbility{
				game.CantBeBlockedStaticBody,
			},
			OracleText: `
			This creature can't be blocked.
		`,
		},
	}
}

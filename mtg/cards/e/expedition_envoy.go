// ExpeditionEnvoy is the card definition for Expedition Envoy.
//
// Type: Creature — Human Scout Ally
// Cost: {W}
//
// Oracle text:
var ExpeditionEnvoy = newExpeditionEnvoy

func newExpeditionEnvoy() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Expedition Envoy",
			ManaCost: opt.Val(cost.Mana{
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Scout, types.Ally},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 1}),
		},
	}
}

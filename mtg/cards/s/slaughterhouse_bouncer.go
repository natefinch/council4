// SlaughterhouseBouncer is the card definition for Slaughterhouse Bouncer.
//
// Type: Creature — Ogre Warrior
// Cost: {4}{B}
//
// Oracle text:
//
//	Hellbent — When this creature dies, if you have no cards in hand, target creature gets -3/-3 until end of turn.
var SlaughterhouseBouncer = newSlaughterhouseBouncer

func newSlaughterhouseBouncer() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Black),
		CardFace: game.CardFace{
			Name: "Slaughterhouse Bouncer",
			ManaCost: opt.Val(cost.Mana{
				cost.O(4),
				cost.B,
			}),
			Colors:    []color.Color{color.Black},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Ogre, types.Warrior},
			Power:     opt.Val(game.PT{Value: 3}),
			Toughness: opt.Val(game.PT{Value: 3}),
			TriggeredAbilities: []game.TriggeredAbility{
				game.TriggeredAbility{
					Text: "Hellbent — When this creature dies, if you have no cards in hand, target creature gets -3/-3 until end of turn.",
					Trigger: game.TriggerCondition{
						Type: game.TriggerWhen,
						Pattern: game.TriggerPattern{
							Event:            game.EventPermanentDied,
							Source:           game.TriggerSourceSelf,
							SubjectSelection: game.Selection{RequiredTypes: []types.Card{types.Creature}},
							StackObjectKind:  game.StackSpell,
							CounterKind:      counter.PlusOnePlusOne,
						},
						InterveningIf: "if you have no cards in hand",
						InterveningCondition: opt.Val(game.Condition{
							Text:                "if you have no cards in hand",
							ControllerHandEmpty: true,
							SourceCounterKind:   counter.PlusOnePlusOne,
						}),
					},
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Targets: []game.TargetSpec{
									game.TargetSpec{
										MinTargets: 1,
										MaxTargets: 1,
										Constraint: "target creature",
										Allow:      game.TargetAllowPermanent,
										Selection:  opt.Val(game.Selection{RequiredTypesAny: []types.Card{types.Creature}}),
									},
								},
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.ModifyPT{
											Object:         game.TargetPermanentReference(0),
											PowerDelta:     game.Fixed(-3),
											ToughnessDelta: game.Fixed(-3),
											Duration:       game.DurationUntilEndOfTurn,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			Hellbent — When this creature dies, if you have no cards in hand, target creature gets -3/-3 until end of turn.
		`,
		},
	}
}

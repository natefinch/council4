// ShatterskullGiant is the card definition for Shatterskull Giant.
//
// Type: Creature — Giant Warrior
// Cost: {2}{R}{R}
//
// Oracle text:
var ShatterskullGiant = newShatterskullGiant

func newShatterskullGiant() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Red),
		CardFace: game.CardFace{
			Name: "Shatterskull Giant",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.R,
				cost.R,
			}),
			Colors:    []color.Color{color.Red},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Giant, types.Warrior},
			Power:     opt.Val(game.PT{Value: 4}),
			Toughness: opt.Val(game.PT{Value: 3}),
		},
	}
}

package s

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// SuffocatingFumes is the card definition for Suffocating Fumes.
//
// Type: Instant
// Cost: {2}{B}
//
// Oracle text:
//
//	Creatures your opponents control get -1/-1 until end of turn.
//	Cycling {2} ({2}, Discard this card: Draw a card.)
var SuffocatingFumes = newSuffocatingFumes

func newSuffocatingFumes() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Black),
		CardFace: game.CardFace{
			Name: "Suffocating Fumes",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.B,
			}),
			Colors: []color.Color{color.Black},
			Types:  []types.Card{types.Instant},
			ActivatedAbilities: []game.ActivatedAbility{
				game.CyclingActivatedAbility(cost.Mana{cost.O(2)}),
			},
			SpellAbility: opt.Val(game.Mode{
				Sequence: []game.Instruction{
					{
						Primitive: game.ApplyContinuous{
							ContinuousEffects: []game.ContinuousEffect{
								game.ContinuousEffect{
									Duration:       game.DurationPermanent,
									Group:          game.BattlefieldGroup(game.Selection{RequiredTypes: []types.Card{types.Creature}, Controller: game.ControllerOpponent}),
									Layer:          game.LayerPowerToughnessModify,
									PowerDelta:     -1,
									ToughnessDelta: -1,
								},
							},
							Duration: game.DurationUntilEndOfTurn,
						},
					},
				},
			}.Ability()),
			OracleText: `
			Creatures your opponents control get -1/-1 until end of turn.
			Cycling {2} ({2}, Discard this card: Draw a card.)
		`,
		},
	}
}

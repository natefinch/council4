// GlassesOfUrza is the card definition for Glasses of Urza.
//
// Type: Artifact
// Cost: {1}
//
// Oracle text:
//
//	{T}: Look at target player's hand.
var GlassesOfUrza = newGlassesOfUrza

func newGlassesOfUrza() *game.CardDef {
	return &game.CardDef{
		CardFace: game.CardFace{
			Name: "Glasses of Urza",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
			}),
			Types: []types.Card{types.Artifact},
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{T}: Look at target player's hand.",
					AdditionalCosts: []cost.Additional{
						cost.Additional{
							Kind:        cost.AdditionalTap,
							CounterKind: counter.PlusOnePlusOne,
						},
					},
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Targets: []game.TargetSpec{
									game.TargetSpec{
										MinTargets: 1,
										MaxTargets: 1,
										Constraint: "target player",
										Allow:      game.TargetAllowPlayer,
									},
								},
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.LookAtHand{
											Player: game.TargetPlayerReference(0),
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{T}: Look at target player's hand.
		`,
		},
	}
}

// Command sourcebindings fingerprints authored code and referenced shared rules.
package main

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/natefinch/council4/internal/sourcebinding"
)

func main() {
	root, err := filepath.Abs(".")
	if err != nil {
		panic(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			break
		}
		parent := filepath.Dir(root)
		if root == parent {
			panic("repository root not found")
		}
		root = parent
	}
	source, err := sourcebinding.Digest(root, "mtg/cards/authored")
	if err != nil {
		panic(err)
	}
	rules, err := sourcebinding.Digest(root, "mtg/rules", "mtg/game", "mtg/cardprogram", "opt")
	if err != nil {
		panic(err)
	}
	shared := fmt.Sprintf("// Code generated by cmd/sourcebindings; DO NOT EDIT.\n\npackage cardprogram\n\nconst SharedRulesRevision = %q\n", rules)
	if err := os.WriteFile(filepath.Join(root, "mtg", "cardprogram", "source_revision.go"), []byte(shared), 0o600); err != nil {
		panic(err)
	}
	data := fmt.Sprintf("// Code generated by cmd/sourcebindings; DO NOT EDIT.\n\npackage authored\n\nconst SourceRevision = %q\nconst RulesRevision = %q\n", source, rules)
	if err := os.WriteFile(filepath.Join(root, "mtg", "cards", "authored", "source_revision.go"), []byte(data), 0o600); err != nil {
		panic(err)
	}
}

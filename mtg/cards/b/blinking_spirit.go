// BlinkingSpirit is the card definition for Blinking Spirit.
//
// Type: Creature — Spirit
// Cost: {3}{W}
//
// Oracle text:
//
//	{0}: Return this creature to its owner's hand.
var BlinkingSpirit = newBlinkingSpirit

func newBlinkingSpirit() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Blinking Spirit",
			ManaCost: opt.Val(cost.Mana{
				cost.O(3),
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Spirit},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{0}: Return this creature to its owner's hand.",
					ManaCost: opt.Val(cost.Mana{
						cost.O(0),
					}),
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.MovePermanent{
											Object:      game.SourcePermanentReference(),
											Destination: zone.Hand,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{0}: Return this creature to its owner's hand.
		`,
		},
	}
}

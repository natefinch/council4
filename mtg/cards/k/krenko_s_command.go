package k

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// KrenkoSCommand is the card definition for Krenko's Command.
//
// Type: Sorcery
// Cost: {1}{R}
//
// Oracle text:
//
//	Create two 1/1 red Goblin creature tokens.
var KrenkoSCommand = newKrenkoSCommand

func newKrenkoSCommand() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Red),
		CardFace: game.CardFace{
			Name: "Krenko's Command",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.R,
			}),
			Colors: []color.Color{color.Red},
			Types:  []types.Card{types.Sorcery},
			SpellAbility: opt.Val(game.Mode{
				Sequence: []game.Instruction{
					{
						Primitive: game.CreateToken{
							Amount: game.Fixed(2),
							Source: game.TokenDef(krenkoSCommandToken),
						},
					},
				},
			}.Ability()),
			OracleText: `
			Create two 1/1 red Goblin creature tokens.
		`,
		},
	}
}

var krenkoSCommandToken = newKrenkoSCommandToken()

func newKrenkoSCommandToken() *game.CardDef {
	return &game.CardDef{
		CardFace: game.CardFace{
			Name:      "Goblin",
			Colors:    []color.Color{color.Red},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Goblin},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 1}),
		},
	}
}

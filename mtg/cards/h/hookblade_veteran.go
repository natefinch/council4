// HookbladeVeteran is the card definition for Hookblade Veteran.
//
// Type: Creature — Human Assassin
// Cost: {U}
//
// Oracle text:
//
//	During your turn, this creature has flying. (It can't be blocked except by creatures with flying or reach.)
var HookbladeVeteran = newHookbladeVeteran

func newHookbladeVeteran() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Blue),
		CardFace: game.CardFace{
			Name: "Hookblade Veteran",
			ManaCost: opt.Val(cost.Mana{
				cost.U,
			}),
			Colors:    []color.Color{color.Blue},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Assassin},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 2}),
			StaticAbilities: []game.StaticAbility{
				game.StaticAbility{
					Text: "During your turn, this creature has flying. (It can't be blocked except by creatures with flying or reach.)",
					Condition: opt.Val(game.Condition{
						Text:                 "During your turn",
						SourceCounterKind:    counter.PlusOnePlusOne,
						SourceControllerTurn: true,
					}),
					ContinuousEffects: []game.ContinuousEffect{
						game.ContinuousEffect{
							Duration:       game.DurationPermanent,
							AffectedSource: true,
							Layer:          game.LayerAbility,
							AddKeywords:    []game.Keyword{game.Flying},
						},
					},
				},
			},
			OracleText: `
			During your turn, this creature has flying. (It can't be blocked except by creatures with flying or reach.)
		`,
		},
	}
}

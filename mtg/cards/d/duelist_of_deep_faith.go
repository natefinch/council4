// DuelistOfDeepFaith is the card definition for Duelist of Deep Faith.
//
// Type: Creature — Phyrexian Soldier
// Cost: {1}{W}
//
// Oracle text:
//
//	Toxic 1 (Players dealt combat damage by this creature also get a poison counter.)
//	During your turn, this creature has first strike.
var DuelistOfDeepFaith = newDuelistOfDeepFaith

func newDuelistOfDeepFaith() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Duelist of Deep Faith",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Phyrexian, types.Soldier},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			StaticAbilities: []game.StaticAbility{
				game.StaticAbility{
					Text: "Toxic 1",
					KeywordAbilities: []game.KeywordAbility{
						game.ToxicKeyword{
							Amount: 1,
						},
					},
				},
				game.StaticAbility{
					Text: "During your turn, this creature has first strike.",
					Condition: opt.Val(game.Condition{
						Text:                 "During your turn",
						SourceCounterKind:    counter.PlusOnePlusOne,
						SourceControllerTurn: true,
					}),
					ContinuousEffects: []game.ContinuousEffect{
						game.ContinuousEffect{
							Duration:       game.DurationPermanent,
							AffectedSource: true,
							Layer:          game.LayerAbility,
							AddKeywords:    []game.Keyword{game.FirstStrike},
						},
					},
				},
			},
			OracleText: `
			Toxic 1 (Players dealt combat damage by this creature also get a poison counter.)
			During your turn, this creature has first strike.
		`,
		},
	}
}

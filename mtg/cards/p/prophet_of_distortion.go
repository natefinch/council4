// ProphetOfDistortion is the card definition for Prophet of Distortion.
//
// Type: Creature — Eldrazi Drone
// Cost: {U}
//
// Oracle text:
//
//	Devoid (This card has no color.)
//	{3}{C}: Draw a card. ({C} represents colorless mana.)
var ProphetOfDistortion = newProphetOfDistortion

func newProphetOfDistortion() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Blue),
		CardFace: game.CardFace{
			Name: "Prophet of Distortion",
			ManaCost: opt.Val(cost.Mana{
				cost.U,
			}),
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Eldrazi, types.Drone},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 2}),
			StaticAbilities: []game.StaticAbility{
				game.DevoidStaticBody,
			},
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{3}{C}: Draw a card. ({C} represents colorless mana.)",
					ManaCost: opt.Val(cost.Mana{
						cost.O(3),
						cost.C,
					}),
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.Draw{
											Amount: game.Fixed(1),
											Player: game.ControllerReference(),
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			Devoid (This card has no color.)
			{3}{C}: Draw a card. ({C} represents colorless mana.)
		`,
		},
	}
}

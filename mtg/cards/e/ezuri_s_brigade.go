// EzuriSBrigade is the card definition for Ezuri's Brigade.
//
// Type: Creature — Elf Warrior
// Cost: {2}{G}{G}
//
// Oracle text:
//
//	Metalcraft — As long as you control three or more artifacts, this creature gets +4/+4 and has trample.
var EzuriSBrigade = newEzuriSBrigade

func newEzuriSBrigade() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Ezuri's Brigade",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.G,
				cost.G,
			}),
			Colors:    []color.Color{color.Green},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Elf, types.Warrior},
			Power:     opt.Val(game.PT{Value: 4}),
			Toughness: opt.Val(game.PT{Value: 4}),
			StaticAbilities: []game.StaticAbility{
				game.StaticAbility{
					Text: "Metalcraft — As long as you control three or more artifacts, this creature gets +4/+4 and has trample.",
					Condition: opt.Val(game.Condition{
						Text: "As long as you control three or more artifacts",
						ControlsMatching: opt.Val(game.SelectionCount{
							Selection: game.Selection{RequiredTypes: []types.Card{types.Artifact}},
							MinCount:  3,
						}),
						SourceCounterKind: counter.PlusOnePlusOne,
					}),
					ContinuousEffects: []game.ContinuousEffect{
						game.ContinuousEffect{
							Duration:       game.DurationPermanent,
							AffectedSource: true,
							Layer:          game.LayerPowerToughnessModify,
							PowerDelta:     4,
							ToughnessDelta: 4,
						},
						game.ContinuousEffect{
							Duration:       game.DurationPermanent,
							AffectedSource: true,
							Layer:          game.LayerAbility,
							AddKeywords:    []game.Keyword{game.Trample},
						},
					},
				},
			},
			OracleText: `
			Metalcraft — As long as you control three or more artifacts, this creature gets +4/+4 and has trample.
		`,
		},
	}
}

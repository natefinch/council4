// BlessedGhoul is the card definition for Blessed Ghoul.
//
// Type: Creature — Zombie Cleric
// Cost: {W/B}
//
// Oracle text:
//
//	Lifelink
//	{2}{W/B}: Return this card from your graveyard to your hand.
var BlessedGhoul = newBlessedGhoul

func newBlessedGhoul() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White, color.Black),
		CardFace: game.CardFace{
			Name: "Blessed Ghoul",
			ManaCost: opt.Val(cost.Mana{
				cost.HybridMana(mana.W, mana.B),
			}),
			Colors:    []color.Color{color.Black, color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Zombie, types.Cleric},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 1}),
			StaticAbilities: []game.StaticAbility{
				game.LifelinkStaticBody,
			},
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{2}{W/B}: Return this card from your graveyard to your hand.",
					ManaCost: opt.Val(cost.Mana{
						cost.O(2),
						cost.HybridMana(mana.W, mana.B),
					}),
					ZoneOfFunction: zone.Graveyard,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.MoveCard{
											Card: game.CardReference{
												Kind: game.CardReferenceSource,
											},
											FromZone:    zone.Graveyard,
											Destination: zone.Hand,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			Lifelink
			{2}{W/B}: Return this card from your graveyard to your hand.
		`,
		},
	}
}

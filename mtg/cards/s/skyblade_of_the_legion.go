// SkybladeOfTheLegion is the card definition for Skyblade of the Legion.
//
// Type: Creature — Vampire Soldier
// Cost: {1}{W}
//
// Oracle text:
//
//	Flying
var SkybladeOfTheLegion = newSkybladeOfTheLegion

func newSkybladeOfTheLegion() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Skyblade of the Legion",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Vampire, types.Soldier},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 3}),
			StaticAbilities: []game.StaticAbility{
				game.FlyingStaticBody,
			},
			OracleText: `
			Flying
		`,
		},
	}
}

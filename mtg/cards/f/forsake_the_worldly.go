// ForsakeTheWorldly is the card definition for Forsake the Worldly.
//
// Type: Instant
// Cost: {2}{W}
//
// Oracle text:
//
//	Exile target artifact or enchantment.
//	Cycling {2} ({2}, Discard this card: Draw a card.)
var ForsakeTheWorldly = newForsakeTheWorldly

func newForsakeTheWorldly() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Forsake the Worldly",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.W,
			}),
			Colors: []color.Color{color.White},
			Types:  []types.Card{types.Instant},
			ActivatedAbilities: []game.ActivatedAbility{
				game.CyclingActivatedAbility(cost.Mana{cost.O(2)}),
			},
			SpellAbility: opt.Val(game.Mode{
				Targets: []game.TargetSpec{
					game.TargetSpec{
						MinTargets: 1,
						MaxTargets: 1,
						Constraint: "target artifact or enchantment",
						Allow:      game.TargetAllowPermanent,
						Selection:  opt.Val(game.Selection{RequiredTypesAny: []types.Card{types.Artifact, types.Enchantment}}),
					},
				},
				Sequence: []game.Instruction{
					{
						Primitive: game.MovePermanent{
							Object:      game.TargetPermanentReference(0),
							Destination: zone.Exile,
						},
					},
				},
			}.Ability()),
			OracleText: `
			Exile target artifact or enchantment.
			Cycling {2} ({2}, Discard this card: Draw a card.)
		`,
		},
	}
}

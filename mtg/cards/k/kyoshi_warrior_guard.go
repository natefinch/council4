// KyoshiWarriorGuard is the card definition for Kyoshi Warrior Guard.
//
// Type: Creature — Human Warrior Ally
// Cost: {1}{W}
//
// Oracle text:
var KyoshiWarriorGuard = newKyoshiWarriorGuard

func newKyoshiWarriorGuard() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Kyoshi Warrior Guard",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Warrior, types.Ally},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 3}),
		},
	}
}

// BrokersInitiate is the card definition for Brokers Initiate.
//
// Type: Creature — Cat Citizen
// Cost: {W}
//
// Oracle text:
//
//	{4}{G/U}: This creature has base power and toughness 5/5 until end of turn.
var BrokersInitiate = newBrokersInitiate

func newBrokersInitiate() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White, color.Blue, color.Green),
		CardFace: game.CardFace{
			Name: "Brokers Initiate",
			ManaCost: opt.Val(cost.Mana{
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Cat, types.Citizen},
			Power:     opt.Val(game.PT{Value: 0}),
			Toughness: opt.Val(game.PT{Value: 4}),
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{4}{G/U}: This creature has base power and toughness 5/5 until end of turn.",
					ManaCost: opt.Val(cost.Mana{
						cost.O(4),
						cost.HybridMana(mana.G, mana.U),
					}),
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.ApplyContinuous{
											Object: opt.Val(game.SourcePermanentReference()),
											ContinuousEffects: []game.ContinuousEffect{
												game.ContinuousEffect{
													Duration: game.DurationPermanent,
													Layer:    game.LayerPowerToughnessSet,
													SetPower: opt.Val(game.PT{
														Value: 5,
													}),
													SetToughness: opt.Val(game.PT{
														Value: 5,
													}),
												},
											},
											Duration: game.DurationUntilEndOfTurn,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{4}{G/U}: This creature has base power and toughness 5/5 until end of turn.
		`,
		},
	}
}

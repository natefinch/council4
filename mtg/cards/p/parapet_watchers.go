// ParapetWatchers is the card definition for Parapet Watchers.
//
// Type: Creature — Kithkin Soldier
// Cost: {2}{U}
//
// Oracle text:
//
//	{W/U}: This creature gets +0/+1 until end of turn.
var ParapetWatchers = newParapetWatchers

func newParapetWatchers() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White, color.Blue),
		CardFace: game.CardFace{
			Name: "Parapet Watchers",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.U,
			}),
			Colors:    []color.Color{color.Blue},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Kithkin, types.Soldier},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{W/U}: This creature gets +0/+1 until end of turn.",
					ManaCost: opt.Val(cost.Mana{
						cost.HybridMana(mana.W, mana.U),
					}),
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.ModifyPT{
											Object:         game.SourcePermanentReference(),
											ToughnessDelta: game.Fixed(1),
											Duration:       game.DurationUntilEndOfTurn,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{W/U}: This creature gets +0/+1 until end of turn.
		`,
		},
	}
}

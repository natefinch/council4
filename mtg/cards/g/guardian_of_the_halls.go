// GuardianOfTheHalls is the card definition for Guardian of the Halls.
//
// Type: Creature — Elf Soldier
// Cost: {1}{G}
//
// Oracle text:
//
//	Trample
//	{5}{G}{G}: Put three +1/+1 counters on this creature.
var GuardianOfTheHalls = newGuardianOfTheHalls

func newGuardianOfTheHalls() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Guardian of the Halls",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.G,
			}),
			Colors:    []color.Color{color.Green},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Elf, types.Soldier},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			StaticAbilities: []game.StaticAbility{
				game.TrampleStaticBody,
			},
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{5}{G}{G}: Put three +1/+1 counters on this creature.",
					ManaCost: opt.Val(cost.Mana{
						cost.O(5),
						cost.G,
						cost.G,
					}),
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.AddCounter{
											Amount:      game.Fixed(3),
											Object:      game.SourcePermanentReference(),
											CounterKind: counter.PlusOnePlusOne,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			Trample
			{5}{G}{G}: Put three +1/+1 counters on this creature.
		`,
		},
	}
}

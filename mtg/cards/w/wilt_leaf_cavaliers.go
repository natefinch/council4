// WiltLeafCavaliers is the card definition for Wilt-Leaf Cavaliers.
//
// Type: Creature — Elf Knight
// Cost: {G/W}{G/W}{G/W}
//
// Oracle text:
//
//	Vigilance
var WiltLeafCavaliers = newWiltLeafCavaliers

func newWiltLeafCavaliers() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White, color.Green),
		CardFace: game.CardFace{
			Name: "Wilt-Leaf Cavaliers",
			ManaCost: opt.Val(cost.Mana{
				cost.HybridMana(mana.G, mana.W),
				cost.HybridMana(mana.G, mana.W),
				cost.HybridMana(mana.G, mana.W),
			}),
			Colors:    []color.Color{color.Green, color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Elf, types.Knight},
			Power:     opt.Val(game.PT{Value: 3}),
			Toughness: opt.Val(game.PT{Value: 4}),
			StaticAbilities: []game.StaticAbility{
				game.VigilanceStaticBody,
			},
			OracleText: `
			Vigilance
		`,
		},
	}
}

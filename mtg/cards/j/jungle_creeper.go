// JungleCreeper is the card definition for Jungle Creeper.
//
// Type: Creature — Elemental
// Cost: {1}{B}{G}
//
// Oracle text:
//
//	{3}{B}{G}: Return this card from your graveyard to your hand.
var JungleCreeper = newJungleCreeper

func newJungleCreeper() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Black, color.Green),
		CardFace: game.CardFace{
			Name: "Jungle Creeper",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.B,
				cost.G,
			}),
			Colors:    []color.Color{color.Black, color.Green},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Elemental},
			Power:     opt.Val(game.PT{Value: 3}),
			Toughness: opt.Val(game.PT{Value: 3}),
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{3}{B}{G}: Return this card from your graveyard to your hand.",
					ManaCost: opt.Val(cost.Mana{
						cost.O(3),
						cost.B,
						cost.G,
					}),
					ZoneOfFunction: zone.Graveyard,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.MoveCard{
											Card: game.CardReference{
												Kind: game.CardReferenceSource,
											},
											FromZone:    zone.Graveyard,
											Destination: zone.Hand,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{3}{B}{G}: Return this card from your graveyard to your hand.
		`,
		},
	}
}

// SporecrownThallid is the card definition for Sporecrown Thallid.
//
// Type: Creature — Fungus
// Cost: {1}{G}
//
// Oracle text:
//
//	Each other creature you control that's a Fungus or Saproling gets +1/+1.
var SporecrownThallid = newSporecrownThallid

func newSporecrownThallid() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Sporecrown Thallid",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.G,
			}),
			Colors:    []color.Color{color.Green},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Fungus},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			StaticAbilities: []game.StaticAbility{
				game.StaticAbility{
					Text: "Each other creature you control that's a Fungus or Saproling gets +1/+1.",
					ContinuousEffects: []game.ContinuousEffect{
						game.ContinuousEffect{
							Duration:       game.DurationPermanent,
							Group:          game.ObjectControlledGroupExcluding(game.SourcePermanentReference(), game.Selection{SubtypesAny: []types.Sub{types.Sub("Fungus"), types.Sub("Saproling")}}, game.SourcePermanentReference()),
							Layer:          game.LayerPowerToughnessModify,
							PowerDelta:     1,
							ToughnessDelta: 1,
						},
					},
				},
			},
			OracleText: `
			Each other creature you control that's a Fungus or Saproling gets +1/+1.
		`,
		},
	}
}

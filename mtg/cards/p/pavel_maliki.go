// PavelMaliki is the card definition for Pavel Maliki.
//
// Type: Legendary Creature — Human
// Cost: {4}{B}{R}
//
// Oracle text:
//
//	{B}{R}: Pavel Maliki gets +1/+0 until end of turn.
var PavelMaliki = newPavelMaliki

func newPavelMaliki() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Black, color.Red),
		CardFace: game.CardFace{
			Name: "Pavel Maliki",
			ManaCost: opt.Val(cost.Mana{
				cost.O(4),
				cost.B,
				cost.R,
			}),
			Colors:     []color.Color{color.Black, color.Red},
			Supertypes: []types.Super{types.Legendary},
			Types:      []types.Card{types.Creature},
			Subtypes:   []types.Sub{types.Human},
			Power:      opt.Val(game.PT{Value: 5}),
			Toughness:  opt.Val(game.PT{Value: 3}),
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{B}{R}: Pavel Maliki gets +1/+0 until end of turn.",
					ManaCost: opt.Val(cost.Mana{
						cost.B,
						cost.R,
					}),
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.ModifyPT{
											Object:     game.SourcePermanentReference(),
											PowerDelta: game.Fixed(1),
											Duration:   game.DurationUntilEndOfTurn,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{B}{R}: Pavel Maliki gets +1/+0 until end of turn.
		`,
		},
	}
}

// DismissivePyromancer is the card definition for Dismissive Pyromancer.
//
// Type: Creature — Human Wizard
// Cost: {1}{R}
//
// Oracle text:
//
//	{R}, {T}, Discard a card: Draw a card.
//	{2}{R}, {T}, Sacrifice this creature: It deals 4 damage to target creature.
var DismissivePyromancer = newDismissivePyromancer


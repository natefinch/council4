// ToothOfRamos is the card definition for Tooth of Ramos.
//
// Type: Artifact
// Cost: {3}
//
// Oracle text:
//
//	{T}: Add {W}.
//	Sacrifice this artifact: Add {W}.
var ToothOfRamos = newToothOfRamos

func newToothOfRamos() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Tooth of Ramos",
			ManaCost: opt.Val(cost.Mana{
				cost.O(3),
			}),
			Types: []types.Card{types.Artifact},
			ManaAbilities: []game.ManaAbility{
				game.TapManaAbility(mana.W),
				game.ManaAbility{
					Text: "Sacrifice this artifact: Add {W}.",
					AdditionalCosts: []cost.Additional{
						cost.Additional{
							Kind:        cost.AdditionalSacrificeSource,
							Text:        "Sacrifice this artifact",
							Amount:      1,
							CounterKind: counter.PlusOnePlusOne,
						},
					},
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.AddMana{
											Amount:    game.Fixed(1),
											ManaColor: mana.W,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{T}: Add {W}.
			Sacrifice this artifact: Add {W}.
		`,
		},
	}
}

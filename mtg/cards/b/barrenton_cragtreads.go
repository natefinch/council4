// BarrentonCragtreads is the card definition for Barrenton Cragtreads.
//
// Type: Creature — Kithkin Scout
// Cost: {2}{W/U}{W/U}
//
// Oracle text:
//
//	This creature can't be blocked by red creatures.
var BarrentonCragtreads = newBarrentonCragtreads

func newBarrentonCragtreads() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White, color.Blue),
		CardFace: game.CardFace{
			Name: "Barrenton Cragtreads",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.HybridMana(mana.W, mana.U),
				cost.HybridMana(mana.W, mana.U),
			}),
			Colors:    []color.Color{color.Blue, color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Kithkin, types.Scout},
			Power:     opt.Val(game.PT{Value: 3}),
			Toughness: opt.Val(game.PT{Value: 3}),
			StaticAbilities: []game.StaticAbility{
				game.StaticAbility{
					Text: "This creature can't be blocked by red creatures.",
					RuleEffects: []game.RuleEffect{
						game.RuleEffect{
							Kind:           game.RuleEffectCantBeBlockedByCreaturesWith,
							AffectedSource: true,
							Duration:       game.DurationPermanent,
							BlockerRestriction: game.BlockerRestriction{
								Kind:  game.BlockerRestrictionColor,
								Color: color.Red,
							},
						},
					},
				},
			},
			OracleText: `
			This creature can't be blocked by red creatures.
		`,
		},
	}
}

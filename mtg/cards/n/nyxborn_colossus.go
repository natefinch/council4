// NyxbornColossus is the card definition for Nyxborn Colossus.
//
// Type: Enchantment Creature — Giant
// Cost: {3}{G}{G}{G}
//
// Oracle text:
var NyxbornColossus = newNyxbornColossus

func newNyxbornColossus() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Nyxborn Colossus",
			ManaCost: opt.Val(cost.Mana{
				cost.O(3),
				cost.G,
				cost.G,
				cost.G,
			}),
			Colors:    []color.Color{color.Green},
			Types:     []types.Card{types.Enchantment, types.Creature},
			Subtypes:  []types.Sub{types.Giant},
			Power:     opt.Val(game.PT{Value: 6}),
			Toughness: opt.Val(game.PT{Value: 7}),
		},
	}
}

package rules

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/zone"
	"github.com/natefinch/council4/opt"
)

// cardHasRebound reports whether the spell's resolving face carries the Rebound
// keyword (CR 702.88).
func cardHasRebound(spellDef *game.CardDef) bool {
	return spellDef.HasKeyword(game.Rebound)
}

const reboundReplacementLabel = "Rebound (CR 702.88a)"

// reboundAppliesToResolvingSpell reports whether a resolving spell's rebound
// replacement can apply to its move to the graveyard. "If this spell was cast
// from your hand" (CR 702.88a) refers to the spell's controller, so a spell
// whose control changed after it was cast doesn't rebound for its new
// controller, and copies are never cast.
func reboundAppliesToResolvingSpell(obj *game.StackObject, spellDef *game.CardDef) bool {
	return !obj.Copy && obj.SourceZone == zone.Hand && stackSpellCaster(obj) == obj.Controller && cardHasRebound(spellDef)
}

// reboundReplacement is rebound's "instead of putting it into your graveyard
// as it resolves, exile it" (CR 702.88a). It is a static ability of the spell,
// not a self-replacement, so it competes with other replacements of the same
// stack-to-graveyard move and the spell's controller chooses the order (CR
// 616.1). Its ID is only a local key.
func reboundReplacement(obj *game.StackObject, card *game.CardInstance) game.ReplacementEffect {
	return game.ReplacementEffect{
		ID: obj.ID, Controller: obj.Controller, SourceCardID: card.ID,
		Description: reboundReplacementLabel, MatchEvent: game.EventZoneChanged,
		MatchFromZone: true, FromZone: zone.Stack,
		MatchToZone: true, ToZone: zone.Graveyard, ReplaceToZone: zone.Exile,
	}
}

// reboundDelayedTriggerText is the public text of rebound's delayed triggered
// ability (CR 702.88a).
const reboundDelayedTriggerText = "At the beginning of your next upkeep, you may cast this card from exile without paying its mana cost."

// recordReboundExile creates rebound's delayed triggered ability (CR 702.88a).
// Callers create it only when the rebound replacement was applied and the card
// actually arrived in its owner's exile; a card exiled by another redirect
// (Dauthi Voidwalker, Rest in Peace) or sent elsewhere gets no delayed cast.
// The rebound replacement is generated by the spell's static ability, so the
// spell is the trigger's source and its controller as the replacement applied
// controls the trigger (CR 603.7f). The trigger captures the exiled card's zone
// incarnation, so a card that leaves exile is no longer offered (CR 603.7c,
// 400.7).
func recordReboundExile(g *game.Game, obj *game.StackObject, card *game.CardInstance) {
	g.DelayedTriggers = append(g.DelayedTriggers, game.DelayedTrigger{
		ID:                      g.IDGen.Next(),
		SourceID:                card.ID,
		SourceObjectID:          obj.ID,
		Controller:              obj.Controller,
		CreatedTurn:             g.Turn.TurnNumber,
		Timing:                  game.DelayedAtBeginningOfYourNextUpkeep,
		Ability:                 game.TriggeredAbility{Text: reboundDelayedTriggerText},
		CapturedCardID:          card.ID,
		CapturedCardZoneVersion: card.ZoneVersion,
		Rebound:                 true,
	})
}

// resolveReboundTrigger resolves rebound's delayed triggered ability: its
// controller may cast the captured card from exile without paying its mana
// cost (CR 702.88a). The cast follows the alternative-cost rules (CR 702.88b,
// 601.2b, 601.2f-h): additional costs, cost increases and reductions still
// apply to the free alternative cost, so an unpayable total cost leaves the
// card in exile. A card that left exile, even if it has since returned, is a
// new object the ability doesn't affect (CR 603.7c, 400.7). A card left uncast
// stays in exile with no later chance.
func (e *Engine) resolveReboundTrigger(g *game.Game, obj *game.StackObject, agents [game.NumPlayers]PlayerAgent, log *TurnLog) string {
	card, ok := g.GetCardInstance(obj.CapturedCardID)
	if !ok || card.ZoneVersion != obj.CapturedCardZoneVersion {
		return "resolved"
	}
	owner, ok := playerByID(g, card.Owner)
	if !ok || !owner.Exile.Contains(card.ID) {
		return "resolved"
	}
	e.chooseAndCastFreeSpellFromSourceMay(g, owner, obj.Controller, card.ID, zone.Exile, game.Selection{}, opt.V[int]{}, false, true, agents, log)
	return "resolved"
}

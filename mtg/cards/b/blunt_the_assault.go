package b

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// BluntTheAssault is the card definition for Blunt the Assault.
//
// Type: Instant
// Cost: {3}{G}
//
// Oracle text:
//
//	You gain 1 life for each creature on the battlefield. Prevent all combat damage that would be dealt this turn.
var BluntTheAssault = newBluntTheAssault

func newBluntTheAssault() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Blunt the Assault",
			ManaCost: opt.Val(cost.Mana{
				cost.O(3),
				cost.G,
			}),
			Colors: []color.Color{color.Green},
			Types:  []types.Card{types.Instant},
			SpellAbility: opt.Val(game.Mode{
				Sequence: []game.Instruction{
					{
						Primitive: game.GainLife{
							Amount: game.Dynamic(game.DynamicAmount{
								Kind:       game.DynamicAmountCountSelector,
								Multiplier: 1,
								Group:      game.BattlefieldGroup(game.Selection{RequiredTypes: []types.Card{types.Creature}}),
							}),
							Player: game.ControllerReference(),
						},
					},
					{
						Primitive: game.PreventDamage{
							All:        true,
							CombatOnly: true,
							Global:     true,
						},
					},
				},
			}.Ability()),
			OracleText: `
			You gain 1 life for each creature on the battlefield. Prevent all combat damage that would be dealt this turn.
		`,
		},
	}
}

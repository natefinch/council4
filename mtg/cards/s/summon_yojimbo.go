// SummonYojimbo is the card definition for Summon: Yojimbo.
//
// Type: Enchantment Creature — Saga Samurai
// Cost: {3}{W}
//
// Oracle text:
//
//	(As this Saga enters and after your draw step, add a lore counter. Sacrifice after IV.)
//	I — Exile target artifact, enchantment, or tapped creature an opponent controls.
//	II, III — Until your next turn, creatures can't attack you unless their controller pays {2} for each of those creatures.
//	IV — Create X Treasure tokens, where X is the number of opponents who control a creature with power 4 or greater.
//	Vigilance
var SummonYojimbo = newSummonYojimbo

func newSummonYojimbo() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Summon: Yojimbo",
			ManaCost: opt.Val(cost.Mana{
				cost.O(3),
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Enchantment, types.Creature},
			Subtypes:  []types.Sub{types.Saga, types.Samurai},
			Power:     opt.Val(game.PT{Value: 5}),
			Toughness: opt.Val(game.PT{Value: 5}),
			StaticAbilities: []game.StaticAbility{
				game.VigilanceStaticBody,
			},
			ChapterAbilities: []game.ChapterAbility{
				game.ChapterAbility{
					Text:     "I — Exile target artifact, enchantment, or tapped creature an opponent controls.",
					Chapters: []int{1},
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Targets: []game.TargetSpec{
									game.TargetSpec{
										MinTargets: 1,
										MaxTargets: 1,
										Allow:      game.TargetAllowPermanent,
										Selection:  opt.Val(game.Selection{AnyOf: []game.Selection{game.Selection{RequiredTypesAny: []types.Card{types.Artifact}}, game.Selection{RequiredTypesAny: []types.Card{types.Enchantment}}, game.Selection{RequiredTypesAny: []types.Card{types.Creature}, Tapped: game.TriTrue}}, Controller: game.ControllerOpponent}),
									},
								},
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.MovePermanent{
											Object:      game.TargetPermanentReference(0),
											Destination: zone.Exile,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
				game.ChapterAbility{
					Text:     "II, III — Until your next turn, creatures can't attack you unless their controller pays {2} for each of those creatures.",
					Chapters: []int{2, 3},
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.ApplyRule{
											RuleEffects: []game.RuleEffect{
												game.RuleEffect{
													Kind:             game.RuleEffectAttackTax,
													Duration:         game.DurationPermanent,
													AffectedPlayer:   game.PlayerYou,
													AttackTaxGeneric: 2,
												},
											},
											Duration: game.DurationUntilYourNextTurn,
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
				game.ChapterAbility{
					Text:     "IV — Create X Treasure tokens, where X is the number of opponents who control a creature with power 4 or greater.",
					Chapters: []int{4},
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.CreateToken{
											Amount: game.Dynamic(game.DynamicAmount{
												Kind:       game.DynamicAmountOpponentControllingCount,
												Multiplier: 1,
												Group:      game.BattlefieldGroup(game.Selection{RequiredTypes: []types.Card{types.Creature}, Controller: game.ControllerYou, Power: opt.Val(compare.Int{Op: compare.GreaterOrEqual, Value: 4})}),
											}),
											Source: game.TokenDef(summonYojimboToken),
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			(As this Saga enters and after your draw step, add a lore counter. Sacrifice after IV.)
			I — Exile target artifact, enchantment, or tapped creature an opponent controls.
			II, III — Until your next turn, creatures can't attack you unless their controller pays {2} for each of those creatures.
			IV — Create X Treasure tokens, where X is the number of opponents who control a creature with power 4 or greater.
			Vigilance
		`,
		},
	}
}

var summonYojimboToken = newSummonYojimboToken()


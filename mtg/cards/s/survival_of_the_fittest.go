// SurvivalOfTheFittest is the card definition for Survival of the Fittest.
//
// Type: Enchantment
// Cost: {1}{G}
//
// Oracle text:
//
//	{G}, Discard a creature card: Search your library for a creature card, reveal that card, put it into your hand, then shuffle.
var SurvivalOfTheFittest = newSurvivalOfTheFittest

func newSurvivalOfTheFittest() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Survival of the Fittest",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.G,
			}),
			Colors: []color.Color{color.Green},
			Types:  []types.Card{types.Enchantment},
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{G}, Discard a creature card: Search your library for a creature card, reveal that card, put it into your hand, then shuffle.",
					ManaCost: opt.Val(cost.Mana{
						cost.G,
					}),
					AdditionalCosts: []cost.Additional{
						cost.Additional{
							Kind:          cost.AdditionalDiscard,
							Text:          "Discard a creature card",
							Amount:        1,
							MatchCardType: true,
							CardType:      types.Creature,
							Source:        zone.Hand,
							CounterKind:   counter.PlusOnePlusOne,
						},
					},
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.Search{
											Player: game.ControllerReference(),
											Spec: game.SearchSpec{
												SourceZone:  zone.Library,
												Destination: zone.Hand,
												Filter:      game.Selection{RequiredTypes: []types.Card{types.Creature}},
												Reveal:      true,
											},
											Amount: game.Fixed(1),
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{G}, Discard a creature card: Search your library for a creature card, reveal that card, put it into your hand, then shuffle.
		`,
		},
	}
}

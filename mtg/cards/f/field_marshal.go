package f

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// FieldMarshal is the card definition for Field Marshal.
//
// Type: Creature — Human Soldier
// Cost: {1}{W}{W}
//
// Oracle text:
//
//	Other Soldier creatures get +1/+1 and have first strike. (They deal combat damage before creatures without first strike.)
var FieldMarshal = newFieldMarshal

func newFieldMarshal() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Field Marshal",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.W,
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Soldier},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			StaticAbilities: []game.StaticAbility{
				game.StaticAbility{
					Text: "Other Soldier creatures get +1/+1 and have first strike. (They deal combat damage before creatures without first strike.)",
					ContinuousEffects: []game.ContinuousEffect{
						game.ContinuousEffect{
							Duration:       game.DurationPermanent,
							Group:          game.BattlefieldGroupExcluding(game.Selection{SubtypesAny: []types.Sub{types.Sub("Soldier")}}, game.SourcePermanentReference()),
							Layer:          game.LayerPowerToughnessModify,
							PowerDelta:     1,
							ToughnessDelta: 1,
						},
						game.ContinuousEffect{
							Duration:    game.DurationPermanent,
							Group:       game.BattlefieldGroupExcluding(game.Selection{SubtypesAny: []types.Sub{types.Sub("Soldier")}}, game.SourcePermanentReference()),
							Layer:       game.LayerAbility,
							AddKeywords: []game.Keyword{game.FirstStrike},
						},
					},
				},
			},
			OracleText: `
			Other Soldier creatures get +1/+1 and have first strike. (They deal combat damage before creatures without first strike.)
		`,
		},
	}
}

// WastelandScorpion is the card definition for Wasteland Scorpion.
//
// Type: Creature — Scorpion
// Cost: {2}{B}
//
// Oracle text:
//
//	Deathtouch
//	Cycling {2} ({2}, Discard this card: Draw a card.)
var WastelandScorpion = newWastelandScorpion

func newWastelandScorpion() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Black),
		CardFace: game.CardFace{
			Name: "Wasteland Scorpion",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.B,
			}),
			Colors:    []color.Color{color.Black},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Scorpion},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			StaticAbilities: []game.StaticAbility{
				game.DeathtouchStaticBody,
			},
			ActivatedAbilities: []game.ActivatedAbility{
				game.CyclingActivatedAbility(cost.Mana{cost.O(2)}),
			},
			OracleText: `
			Deathtouch
			Cycling {2} ({2}, Discard this card: Draw a card.)
		`,
		},
	}
}

// MerfolkOfThePearlTrident is the card definition for Merfolk of the Pearl Trident.
//
// Type: Creature — Merfolk
// Cost: {U}
//
// Oracle text:
var MerfolkOfThePearlTrident = newMerfolkOfThePearlTrident

func newMerfolkOfThePearlTrident() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Blue),
		CardFace: game.CardFace{
			Name: "Merfolk of the Pearl Trident",
			ManaCost: opt.Val(cost.Mana{
				cost.U,
			}),
			Colors:    []color.Color{color.Blue},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Merfolk},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 1}),
		},
	}
}

// WhiptailWurm is the card definition for Whiptail Wurm.
//
// Type: Creature — Wurm
// Cost: {6}{G}
//
// Oracle text:
var WhiptailWurm = newWhiptailWurm

func newWhiptailWurm() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Whiptail Wurm",
			ManaCost: opt.Val(cost.Mana{
				cost.O(6),
				cost.G,
			}),
			Colors:    []color.Color{color.Green},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Wurm},
			Power:     opt.Val(game.PT{Value: 8}),
			Toughness: opt.Val(game.PT{Value: 5}),
		},
	}
}

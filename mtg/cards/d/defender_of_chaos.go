package d

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// DefenderOfChaos is the card definition for Defender of Chaos.
//
// Type: Creature — Human Knight
// Cost: {2}{R}
//
// Oracle text:
//
//	Flash
//	Protection from white
var DefenderOfChaos = newDefenderOfChaos

func newDefenderOfChaos() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Red),
		CardFace: game.CardFace{
			Name: "Defender of Chaos",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.R,
			}),
			Colors:    []color.Color{color.Red},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Knight},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 1}),
			StaticAbilities: []game.StaticAbility{
				game.FlashStaticBody,
				game.ProtectionFromColorsStaticAbility(color.White),
			},
			OracleText: `
			Flash
			Protection from white
		`,
		},
	}
}

// DragonSEyeSentry is the card definition for Dragon's Eye Sentry.
//
// Type: Creature — Human Monk
// Cost: {W}
//
// Oracle text:
//
//	Defender, first strike
var DragonSEyeSentry = newDragonSEyeSentry

func newDragonSEyeSentry() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White),
		CardFace: game.CardFace{
			Name: "Dragon's Eye Sentry",
			ManaCost: opt.Val(cost.Mana{
				cost.W,
			}),
			Colors:    []color.Color{color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Monk},
			Power:     opt.Val(game.PT{Value: 1}),
			Toughness: opt.Val(game.PT{Value: 3}),
			StaticAbilities: []game.StaticAbility{
				game.DefenderStaticBody,
				game.FirstStrikeStaticBody,
			},
			OracleText: `
			Defender, first strike
		`,
		},
	}
}

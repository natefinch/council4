package s

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/counter"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// SnakeOfTheGoldenGrove is the card definition for Snake of the Golden Grove.
//
// Type: Creature — Snake
// Cost: {4}{G}
//
// Oracle text:
//
//	Tribute 3 (As this creature enters, an opponent of your choice may put three +1/+1 counters on it.)
//	When this creature enters, if tribute wasn't paid, you gain 4 life.
var SnakeOfTheGoldenGrove = newSnakeOfTheGoldenGrove

func newSnakeOfTheGoldenGrove() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Snake of the Golden Grove",
			ManaCost: opt.Val(cost.Mana{
				cost.O(4),
				cost.G,
			}),
			Colors:    []color.Color{color.Green},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Snake},
			Power:     opt.Val(game.PT{Value: 4}),
			Toughness: opt.Val(game.PT{Value: 4}),
			TriggeredAbilities: []game.TriggeredAbility{
				game.TriggeredAbility{
					Text: "When this creature enters, if tribute wasn't paid, you gain 4 life.",
					Trigger: game.TriggerCondition{
						Type: game.TriggerWhen,
						Pattern: game.TriggerPattern{
							Event:           game.EventPermanentEnteredBattlefield,
							Source:          game.TriggerSourceSelf,
							StackObjectKind: game.StackSpell,
							CounterKind:     counter.PlusOnePlusOne,
						},
						InterveningIf: "if tribute wasn't paid",
						InterveningCondition: opt.Val(game.Condition{
							Text:                 "if tribute wasn't paid",
							SourceCounterKind:    counter.PlusOnePlusOne,
							SourceTributeNotPaid: true,
						}),
					},
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.GainLife{
											Amount: game.Fixed(4),
											Player: game.ControllerReference(),
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			ReplacementAbilities: []game.ReplacementAbility{
				game.TributeReplacement("As this creature enters, an opponent of your choice may put 3 +1/+1 counters on it.", 3),
			},
			OracleText: `
			Tribute 3 (As this creature enters, an opponent of your choice may put three +1/+1 counters on it.)
			When this creature enters, if tribute wasn't paid, you gain 4 life.
		`,
		},
	}
}

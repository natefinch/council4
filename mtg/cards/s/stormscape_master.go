// StormscapeMaster is the card definition for Stormscape Master.
//
// Type: Creature — Human Wizard
// Cost: {2}{U}{U}
//
// Oracle text:
//
//	{W}{W}, {T}: Target creature gains protection from the color of your choice until end of turn.

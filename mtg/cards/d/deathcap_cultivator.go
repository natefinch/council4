// DeathcapCultivator is the card definition for Deathcap Cultivator.
//
// Type: Creature — Human Druid
// Cost: {1}{G}
//
// Oracle text:
//
//	{T}: Add {B} or {G}.
//	Delirium — This creature has deathtouch as long as there are four or more card types among cards in your graveyard.
var DeathcapCultivator = newDeathcapCultivator

func newDeathcapCultivator() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Black, color.Green),
		CardFace: game.CardFace{
			Name: "Deathcap Cultivator",
			ManaCost: opt.Val(cost.Mana{
				cost.O(1),
				cost.G,
			}),
			Colors:    []color.Color{color.Green},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Druid},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 1}),
			StaticAbilities: []game.StaticAbility{
				game.StaticAbility{
					Text: "Delirium — This creature has deathtouch as long as there are four or more card types among cards in your graveyard.",
					Condition: opt.Val(game.Condition{
						Text: "as long as there are four or more card types among cards in your graveyard",
						Aggregates: []game.AggregateComparison{
							game.AggregateComparison{
								Aggregate: game.AggregateControllerGraveyardCardTypeCount,
								Op:        compare.GreaterOrEqual,
								Value:     4,
							},
						},
						SourceCounterKind: counter.PlusOnePlusOne,
					}),
					ContinuousEffects: []game.ContinuousEffect{
						game.ContinuousEffect{
							Duration:       game.DurationPermanent,
							AffectedSource: true,
							Layer:          game.LayerAbility,
							AddKeywords:    []game.Keyword{game.Deathtouch},
						},
					},
				},
			},
			ManaAbilities: []game.ManaAbility{
				game.TapManaChoiceAbility(mana.B, mana.G),
			},
			OracleText: `
			{T}: Add {B} or {G}.
			Delirium — This creature has deathtouch as long as there are four or more card types among cards in your graveyard.
		`,
		},
	}
}

// RakdosShredFreak is the card definition for Rakdos Shred-Freak.
//
// Type: Creature — Human Berserker
// Cost: {B/R}{B/R}
//
// Oracle text:
//
//	Haste
var RakdosShredFreak = newRakdosShredFreak

func newRakdosShredFreak() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Black, color.Red),
		CardFace: game.CardFace{
			Name: "Rakdos Shred-Freak",
			ManaCost: opt.Val(cost.Mana{
				cost.HybridMana(mana.B, mana.R),
				cost.HybridMana(mana.B, mana.R),
			}),
			Colors:    []color.Color{color.Black, color.Red},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Human, types.Berserker},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 1}),
			StaticAbilities: []game.StaticAbility{
				game.HasteStaticBody,
			},
			OracleText: `
			Haste
		`,
		},
	}
}

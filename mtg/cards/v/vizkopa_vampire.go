// VizkopaVampire is the card definition for Vizkopa Vampire.
//
// Type: Creature — Vampire
// Cost: {2}{W/B}
//
// Oracle text:
//
//	Lifelink
var VizkopaVampire = newVizkopaVampire

func newVizkopaVampire() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.White, color.Black),
		CardFace: game.CardFace{
			Name: "Vizkopa Vampire",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.HybridMana(mana.W, mana.B),
			}),
			Colors:    []color.Color{color.Black, color.White},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Vampire},
			Power:     opt.Val(game.PT{Value: 3}),
			Toughness: opt.Val(game.PT{Value: 1}),
			StaticAbilities: []game.StaticAbility{
				game.LifelinkStaticBody,
			},
			OracleText: `
			Lifelink
		`,
		},
	}
}

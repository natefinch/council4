package s

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/mana"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// SunkenHollow is the card definition for Sunken Hollow.
//
// Type: Land — Island Swamp
//
// Oracle text:
//
//	({T}: Add {U} or {B}.)
//	This land enters tapped unless you control two or more basic lands.
var SunkenHollow = newSunkenHollow

func newSunkenHollow() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Blue, color.Black),
		CardFace: game.CardFace{
			Name:     "Sunken Hollow",
			Types:    []types.Card{types.Land},
			Subtypes: []types.Sub{types.Island, types.Swamp},
			ManaAbilities: []game.ManaAbility{
				game.TapManaChoiceAbility(mana.U, mana.B),
			},
			ReplacementAbilities: []game.ReplacementAbility{
				game.EntersTappedIfReplacement("This land enters tapped unless you control two or more basic lands.", &game.Condition{
					Negate: true,
					ControlsMatching: opt.Val(game.SelectionCount{
						Selection: game.Selection{RequiredTypes: []types.Card{types.Land}, Supertypes: []types.Super{types.Basic}},
						MinCount:  2,
					}),
				}),
			},
			OracleText: `
			({T}: Add {U} or {B}.)
			This land enters tapped unless you control two or more basic lands.
		`,
		},
	}
}

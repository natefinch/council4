// AvacynAngelOfHorror is the card definition for Avacyn, Angel of Horror.
//
// Type: Legendary Creature — Angel
// Cost: {5}{B}{B}{B}
//
// Oracle text:
//
//	Flying, deathtouch
//	Whenever Avacyn or another nontoken creature you control dies, return that card to the battlefield under your control at the beginning of the next end step.
var AvacynAngelOfHorror = newAvacynAngelOfHorror


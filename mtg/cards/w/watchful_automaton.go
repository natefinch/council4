// WatchfulAutomaton is the card definition for Watchful Automaton.
//
// Type: Artifact Creature — Construct
// Cost: {3}
//
// Oracle text:
//
//	{2}{U}: Scry 1. (Look at the top card of your library. You may put that card on the bottom.)
var WatchfulAutomaton = newWatchfulAutomaton

func newWatchfulAutomaton() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Blue),
		CardFace: game.CardFace{
			Name: "Watchful Automaton",
			ManaCost: opt.Val(cost.Mana{
				cost.O(3),
			}),
			Types:     []types.Card{types.Artifact, types.Creature},
			Subtypes:  []types.Sub{types.Construct},
			Power:     opt.Val(game.PT{Value: 2}),
			Toughness: opt.Val(game.PT{Value: 2}),
			ActivatedAbilities: []game.ActivatedAbility{
				game.ActivatedAbility{
					Text: "{2}{U}: Scry 1. (Look at the top card of your library. You may put that card on the bottom.)",
					ManaCost: opt.Val(cost.Mana{
						cost.O(2),
						cost.U,
					}),
					ZoneOfFunction: zone.Battlefield,
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.Scry{
											Amount: game.Fixed(1),
											Player: game.ControllerReference(),
										},
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			{2}{U}: Scry 1. (Look at the top card of your library. You may put that card on the bottom.)
		`,
		},
	}
}

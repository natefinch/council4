package f

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// Foxfire is the card definition for Foxfire.
//
// Type: Instant
// Cost: {2}{G}
//
// Oracle text:
//
//	Untap target attacking creature. Prevent all combat damage that would be dealt to and dealt by that creature this turn.
//	Draw a card at the beginning of the next turn's upkeep.
var Foxfire = newFoxfire

func newFoxfire() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Green),
		CardFace: game.CardFace{
			Name: "Foxfire",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.G,
			}),
			Colors: []color.Color{color.Green},
			Types:  []types.Card{types.Instant},
			SpellAbility: opt.Val(game.Mode{
				Targets: []game.TargetSpec{
					game.TargetSpec{
						MinTargets: 1,
						MaxTargets: 1,
						Constraint: "target attacking creature",
						Allow:      game.TargetAllowPermanent,
						Selection:  opt.Val(game.Selection{RequiredTypesAny: []types.Card{types.Creature}, CombatState: game.CombatStateAttacking}),
					},
				},
				Sequence: []game.Instruction{
					{
						Primitive: game.Untap{
							Object: game.TargetPermanentReference(0),
						},
					},
					{
						Primitive: game.PreventDamage{
							Object:     game.TargetPermanentReference(0),
							All:        true,
							CombatOnly: true,
						},
					},
					{
						Primitive: game.PreventDamage{
							Object:     game.TargetPermanentReference(0),
							All:        true,
							CombatOnly: true,
							BySource:   true,
						},
					},
					{
						Primitive: game.CreateDelayedTrigger{
							Trigger: game.DelayedTriggerDef{
								Timing: game.DelayedAtBeginningOfNextUpkeep,
								Content: game.AbilityContent{
									Modes: []game.Mode{
										game.Mode{
											Sequence: []game.Instruction{
												game.Instruction{
													Primitive: game.Draw{
														Amount: game.Fixed(1),
														Player: game.ControllerReference(),
													},
												},
											},
										},
									},
									MinModes: 1,
									MaxModes: 1,
								},
							},
						},
					},
				},
			}.Ability()),
			OracleText: `
			Untap target attacking creature. Prevent all combat damage that would be dealt to and dealt by that creature this turn.
			Draw a card at the beginning of the next turn's upkeep.
		`,
		},
	}
}

// DeathriteShaman is the card definition for Deathrite Shaman.
//
// Type: Creature — Elf Shaman
// Cost: {B/G}
//
// Oracle text:
//
//	{T}: Exile target land card from a graveyard. Add one mana of any color. (Activate only as an instant.)

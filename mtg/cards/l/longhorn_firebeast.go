package l

import (
	"github.com/natefinch/council4/mtg/game"
	"github.com/natefinch/council4/mtg/game/color"
	"github.com/natefinch/council4/mtg/game/cost"
	"github.com/natefinch/council4/mtg/game/counter"
	"github.com/natefinch/council4/mtg/game/types"
	"github.com/natefinch/council4/opt"
)

// LonghornFirebeast is the card definition for Longhorn Firebeast.
//
// Type: Creature — Elemental Ox Beast
// Cost: {2}{R}
//
// Oracle text:
//
//	When this creature enters, any opponent may have it deal 5 damage to them. If a player does, sacrifice this creature.
var LonghornFirebeast = newLonghornFirebeast

func newLonghornFirebeast() *game.CardDef {
	return &game.CardDef{
		ColorIdentity: color.NewIdentity(color.Red),
		CardFace: game.CardFace{
			Name: "Longhorn Firebeast",
			ManaCost: opt.Val(cost.Mana{
				cost.O(2),
				cost.R,
			}),
			Colors:    []color.Color{color.Red},
			Types:     []types.Card{types.Creature},
			Subtypes:  []types.Sub{types.Elemental, types.Ox, types.Beast},
			Power:     opt.Val(game.PT{Value: 3}),
			Toughness: opt.Val(game.PT{Value: 2}),
			TriggeredAbilities: []game.TriggeredAbility{
				game.TriggeredAbility{
					Text: "When this creature enters, any opponent may have it deal 5 damage to them. If a player does, sacrifice this creature.",
					Trigger: game.TriggerCondition{
						Type: game.TriggerWhen,
						Pattern: game.TriggerPattern{
							Event:           game.EventPermanentEnteredBattlefield,
							Source:          game.TriggerSourceSelf,
							StackObjectKind: game.StackSpell,
							CounterKind:     counter.PlusOnePlusOne,
						},
					},
					Content: game.AbilityContent{
						Modes: []game.Mode{
							game.Mode{
								Sequence: []game.Instruction{
									game.Instruction{
										Primitive: game.Damage{
											Amount:    game.Fixed(5),
											Recipient: game.PlayerDamageRecipient(game.GroupOfferMemberReference()),
										},
										Optional:           true,
										OptionalActorGroup: opt.Val(game.OpponentsReference()),
										PublishResult:      game.ResultKey("group-may-have-action"),
									},
									game.Instruction{
										Primitive: game.Sacrifice{
											Object: game.SourcePermanentReference(),
										},
										ResultGate: opt.Val(game.InstructionResultGate{
											Key:      game.ResultKey("group-may-have-action"),
											Accepted: game.TriTrue,
										}),
									},
								},
							},
						},
						MinModes: 1,
						MaxModes: 1,
					},
				},
			},
			OracleText: `
			When this creature enters, any opponent may have it deal 5 damage to them. If a player does, sacrifice this creature.
		`,
		},
	}
}
